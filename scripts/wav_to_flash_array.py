#!/usr/bin/env python3
"""Convert audio into the 48 kHz stereo uint16_t WAV table used by MEDIA_InFLASH.

Needs Python 3 and FFmpeg. By default, clips to five seconds to stay within the
example's 990000-byte playback size; the linker may have less Flash available.
"""

from __future__ import annotations

import argparse
import os
import shutil
import struct
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

RATE = 48_000
CHANNELS = 2
MAX_ARRAY_BYTES = 990_058  # AUDIO_FILE_SZE=990000 and start offset 58


def find_ffmpeg() -> str | None:
    exe = shutil.which("ffmpeg")
    if exe:
        return exe
    local = os.environ.get("LOCALAPPDATA")
    if local:
        root = Path(local) / "Microsoft/WinGet/Packages"
        if root.exists():
            for item in root.glob("Gyan.FFmpeg_*/ffmpeg-*/bin/ffmpeg.exe"):
                if item.is_file():
                    return str(item)
    return None


def make_wav_header(data_size: int, frames: int) -> bytes:
    # 58-byte PCM WAV: fmt chunk (18 bytes), fact chunk (4 bytes), then data.
    byte_rate = RATE * CHANNELS * 2
    block_align = CHANNELS * 2
    riff_size = 50 + data_size
    return struct.pack(
        "<4sI4s4sIHHIIHHH4sII4sI",
        b"RIFF", riff_size, b"WAVE", b"fmt ", 18, 1, CHANNELS,
        RATE, byte_rate, block_align, 16, 0, b"fact", 4, frames,
        b"data", data_size,
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("input", type=Path, help="áudio de entrada (WAV, MP3, etc.)")
    ap.add_argument("-o", "--output", type=Path, default=Path("audio_sample.c"),
                    help="arquivo C a gerar (padrão: ./audio_sample.c)")
    ap.add_argument("--seconds", type=float, default=5.0,
                    help="duração máxima em segundos; padrão 5,0")
    args = ap.parse_args()
    ffmpeg = find_ffmpeg()
    if not ffmpeg:
        ap.error("FFmpeg não encontrado; instale-o e adicione ffmpeg ao PATH")
    if not args.input.is_file():
        ap.error(f"arquivo não encontrado: {args.input}")
    if not (0 < args.seconds <= 5.15):
        ap.error("--seconds deve ser maior que 0 e no máximo 5.15 (limite do exemplo)")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    try:
        with tempfile.TemporaryDirectory(prefix="stm32_flash_") as temp_dir:
            raw_path = Path(temp_dir) / "samples.pcm"
            subprocess.run([
                ffmpeg, "-hide_banner", "-loglevel", "error", "-y",
                "-i", str(args.input.resolve()), "-map", "0:a:0", "-vn",
                "-t", f"{args.seconds:.6f}", "-ac", str(CHANNELS), "-ar", str(RATE),
                "-c:a", "pcm_s16le", "-f", "s16le", str(raw_path),
            ], check=True)
            pcm = raw_path.read_bytes()
        if not pcm or len(pcm) % 4:
            raise ValueError("FFmpeg não gerou amostras estéreo completas")
        frames = len(pcm) // (CHANNELS * 2)
        header = make_wav_header(len(pcm), frames)
        if len(header) != 58:
            raise AssertionError(f"cabeçalho interno inesperado: {len(header)} bytes")
        wav_data = header + pcm
        if len(wav_data) > MAX_ARRAY_BYTES:
            raise ValueError(
                f"vetor com {len(wav_data)} bytes excede o teto do exemplo "
                f"({MAX_ARRAY_BYTES}); reduza --seconds"
            )
        duration = frames / RATE
        macro_size = len(wav_data) - 58
        words = struct.unpack(f"<{len(wav_data)//2}H", wav_data)
        lines = [
            "/* Generated by wav_to_flash_array.py. Review linker map before use. */",
            f"/* PCM: stereo, 16-bit, {RATE} Hz; duration: {duration:.3f} s. */",
            f"/* Set AUDIO_FILE_SZE to {macro_size}u; keep AUIDO_START_ADDRESS at 58. */",
            '#include "stm32f4xx.h"',
            "const uint16_t AUDIO_SAMPLE[] = {",
        ]
        for start in range(0, len(words), 12):
            lines.append("  " + ", ".join(f"0x{v:04x}" for v in words[start:start + 12]) + ",")
        lines.append("};")
        args.output.write_text("\n".join(lines) + "\n", encoding="ascii")

        # Reopen generated container properties from the construction values.
        print(f"C array: {args.output.resolve()}")
        print(f"WAV container: {len(wav_data)} bytes; data: {len(pcm)} bytes; {duration:.3f} s")
        print(f"AUDIO_FILE_SZE = {macro_size}u; AUIDO_START_ADDRESS = 58")
        print("Formato: PCM estéreo, 16 bits, 48000 Hz; cabeçalho WAV de 58 bytes.")
        print("Confira o mapa do linker: a Flash total é 1 MiB e o firmware também ocupa espaço.")
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        print(f"Erro: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
